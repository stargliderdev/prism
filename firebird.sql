SELECT d.NUMERO, d.DATA, c.NOME, r.NUMERO, r.TIPO_DOC,
    r.NUMSERIE, r.CODIGO, a.NOME
FROM DOCUMENTOS_NUMSERIES r, DOCUMENTOS d, CLIENTES c, ARTIGOS a
where (r.TIPO_DOC='FAC' or r.TIPO_DOC='FC') and d.NUMERO=r.NUMERO and d.ENTIDADE_ID = c.ID and a.CODIGO = r.CODIGO
and r.NUMSERIE like '%3647%'
order by r.NUMSERIE